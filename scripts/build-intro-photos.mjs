#!/usr/bin/env node
/**
 * Builds the compressed photo set for the cinematic intro (components/intro).
 *
 *   npm run intro:photos
 *
 * Reads every image in `sourceDir` (lib/intro/intro.config.json), writes:
 *   public/intro/sm/<name>.webp   ≤480px long side  — tunnel frames
 *   public/intro/md/<name>.webp   ≤800px long side  — hero moments
 *   public/intro/final-<name>.webp full size         — the "burn to gold" photo
 * and regenerates lib/intro/photos.json, the manifest the intro reads at runtime.
 *
 * To add projects: drop photos into `sourceDir` and re-run.
 * To change the final photo: edit `finalPhoto` in intro.config.json and re-run.
 */
import { mkdir, readdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONFIG_PATH = path.join(ROOT, 'lib/intro/intro.config.json');
const MANIFEST_PATH = path.join(ROOT, 'lib/intro/photos.json');
const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif']);

const naturalSort = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
const slug = (file) =>
  path
    .parse(file)
    .name.toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

async function encode(input, output, longSide, quality) {
  const info = await sharp(input)
    .rotate() // honour EXIF orientation
    .resize({ width: longSide, height: longSide, fit: 'inside', withoutEnlargement: true })
    .webp({ quality, effort: 5 })
    .toFile(output);
  return { width: info.width, height: info.height, bytes: info.size };
}

async function main() {
  const config = JSON.parse(await readFile(CONFIG_PATH, 'utf8'));
  const sourceDir = path.join(ROOT, config.sourceDir);
  const outDir = path.join(ROOT, config.outputDir);
  const publicBase = '/' + path.relative(path.join(ROOT, 'public'), outDir).split(path.sep).join('/');

  const files = (await readdir(sourceDir))
    .filter((f) => IMAGE_EXT.has(path.extname(f).toLowerCase()))
    .sort(naturalSort);
  if (files.length === 0) throw new Error(`No images found in ${config.sourceDir}`);
  if (!files.includes(config.finalPhoto)) {
    throw new Error(`finalPhoto "${config.finalPhoto}" not found in ${config.sourceDir}`);
  }

  // Encode into a scratch folder and swap it in only when everything succeeded,
  // so a failed run never leaves the manifest pointing at deleted files.
  const workDir = `${outDir}.tmp`;
  await rm(workDir, { recursive: true, force: true });
  await mkdir(path.join(workDir, 'sm'), { recursive: true });
  await mkdir(path.join(workDir, 'md'), { recursive: true });

  // "IMG 1.jpg" and "img-1.png" would share a slug; keep every photo.
  const idByFile = new Map();
  const usedIds = new Set();
  for (const file of files) {
    const base = slug(file) || 'photo';
    let id = base;
    for (let n = 2; usedIds.has(id); n++) id = `${base}-${n}`;
    usedIds.add(id);
    idByFile.set(file, id);
  }

  const { montage } = config;
  let totalSm = 0;
  let totalMd = 0;
  const photos = [];
  for (const file of files) {
    const input = path.join(sourceDir, file);
    const id = idByFile.get(file);
    try {
      const sm = await encode(input, path.join(workDir, 'sm', `${id}.webp`), montage.smallLongSide, montage.smallQuality);
      const md = await encode(input, path.join(workDir, 'md', `${id}.webp`), montage.mediumLongSide, montage.mediumQuality);
      totalSm += sm.bytes;
      totalMd += md.bytes;
      photos.push({
        id,
        sm: `${publicBase}/sm/${id}.webp`,
        md: `${publicBase}/md/${id}.webp`,
        width: md.width,
        height: md.height,
      });
    } catch (err) {
      console.warn(`  ! skipped ${file}: ${err.message}`);
    }
  }

  if (photos.length === 0) throw new Error('No photo could be encoded');
  const finalId = idByFile.get(config.finalPhoto);
  const finalOut = `final-${finalId}.webp`;
  const final = await encode(
    path.join(sourceDir, config.finalPhoto),
    path.join(workDir, finalOut),
    config.final.longSide,
    config.final.quality,
  );
  await rm(outDir, { recursive: true, force: true });
  await rename(workDir, outDir);

  const manifest = {
    note: 'Generated by scripts/build-intro-photos.mjs. Do not edit by hand; run `npm run intro:photos`.',
    final: { id: finalId, src: `${publicBase}/${finalOut}`, width: final.width, height: final.height },
    photos,
  };
  await writeFile(MANIFEST_PATH, JSON.stringify(manifest, null, 2) + '\n');

  const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
  const sourceBytes = (await Promise.all(files.map((f) => stat(path.join(sourceDir, f))))).reduce((s, x) => s + x.size, 0);
  console.log(`Intro photos: ${photos.length} from ${config.sourceDir} (${kb(sourceBytes)} source)`);
  console.log(`  sm total ${kb(totalSm)} · md total ${kb(totalMd)} · final ${kb(final.bytes)} (${finalOut})`);
  console.log(`  manifest → ${path.relative(ROOT, MANIFEST_PATH)}`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
